#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Collection {
    Affinity,
    Buildings,
    Gifts,
    Resources,
    Vehicles,
    Research,
    DisabledResearch,
    Items,
    Milestones,
    Survival,
    CitySurvival,
    AutoSell,
    AutoConvert,
    GlobalFlags,
}

impl Collection {
    pub const ALL: [Self; 14] = [
        Self::Affinity,
        Self::Buildings,
        Self::Gifts,
        Self::Resources,
        Self::Vehicles,
        Self::Research,
        Self::DisabledResearch,
        Self::Items,
        Self::Milestones,
        Self::Survival,
        Self::CitySurvival,
        Self::AutoSell,
        Self::AutoConvert,
        Self::GlobalFlags,
    ];

    pub fn label_key(self) -> &'static str {
        match self {
            Self::Affinity => "affinity",
            Self::Buildings => "buildings",
            Self::Gifts => "gifts",
            Self::Resources => "resources",
            Self::Vehicles => "vehicles",
            Self::Research => "research",
            Self::DisabledResearch => "disabled_research",
            Self::Items => "items",
            Self::Milestones => "milestones",
            Self::Survival | Self::CitySurvival => "upgrades",
            Self::AutoSell => "auto_sell",
            Self::AutoConvert => "auto_convert",
            Self::GlobalFlags => "flags",
        }
    }

    pub fn key(self) -> &'static str {
        match self {
            Self::Affinity => "relationships",
            Self::Buildings => "forceUnlockedBuildings",
            Self::Gifts => "pendingGifts",
            Self::Resources => "resources",
            Self::Vehicles => "unlockedCars",
            Self::Research => "researched",
            Self::DisabledResearch => "disabledResearch",
            Self::Items => "items",
            Self::Milestones => "milestones",
            Self::Survival => "upgradesSpent",
            Self::CitySurvival => "upgradesSpentCity",
            Self::AutoSell => "resourceAutoSellKeepAmt",
            Self::AutoConvert => "resourceAutoConvertKeepAmt",
            Self::GlobalFlags => "globalFlags",
        }
    }

    pub fn matches(self, path: &str) -> bool {
        path.split_once('.')
            .is_some_and(|(key, _)| key == self.key())
    }

    pub fn catalog(self) -> &'static [(i32, &'static str)] {
        match self {
            Self::Affinity | Self::Gifts => NPCS,
            Self::Buildings => BUILDINGS,
            Self::Resources | Self::AutoSell | Self::AutoConvert => RESOURCES,
            Self::Vehicles => VEHICLES,
            Self::Research | Self::DisabledResearch => RESEARCH,
            Self::Items => ITEMS,
            Self::Milestones => MILESTONES,
            Self::Survival | Self::CitySurvival => SURVIVAL,
            _ => &[],
        }
    }

    pub fn is_resource_automation(self) -> bool {
        matches!(self, Self::AutoSell | Self::AutoConvert)
    }
}

